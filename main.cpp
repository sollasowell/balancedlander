#include <string>
#include <vector>

void xor_checksum() {
    int values[4] = {12, 7, 25, 40};
    int checksum = 0;
    for (int i = 0; i < 4; ++i) checksum ^= values[i];
    (void)checksum;
}

void collect_triples() {
    std::vector<int> values;
    for (int i = 1; i <= 5; ++i) values.push_back(i * 3);
    int total = 0;
    for (std::size_t i = 0; i < values.size(); ++i) total += values[i];
    (void)total;
}

void product_range() {
    int acc = 1;
    for (int i = 1; i <= 5; ++i) acc *= i;
    (void)acc;
}

void pick_max() {
    int a = 17, b = 42, c = 8;
    int m = a;
    if (b > m) m = b;
    if (c > m) m = c;
    (void)m;
}

extern "C" int amber_bridge();
extern "C" void calm_prism();
extern "C" void eager_prism();
extern "C" void calm_haven();

int main() {
    xor_checksum();
    collect_triples();
    product_range();
    pick_max();
    calm_prism();
    eager_prism();
    calm_haven();
    return amber_bridge();
}
